"""Makes all the music of the game from the base compositions of composities/actief.py
(ACTIEF, primary: the intro and most derived pieces; MENU, secondary: the menu and derive.SECONDARY_PIECES;
GEVECHT, tertiary: the fight scene, when set; docs/MUZIEK.md):

    tools/muziek/render.sh                         everything, into assets/audio/muziek/
    tools/muziek/render.sh zwervr_intro spel_loop  only these pieces
    tools/muziek/render.sh --uit /some/folder      somewhere else (to listen before replacing)
    ZWERVR_COMPOSITIE=<naam> tools/muziek/render.sh    another first composition than composities/actief.py
    ZWERVR_MENU_COMPOSITIE=<naam> tools/muziek/render.sh   another second (menu) composition
    ZWERVR_GEVECHT_COMPOSITIE=<naam> tools/muziek/render.sh   a third (fight scene) composition

The intro also writes scripts/ui/intro_timing.gd: the moments (MOMENTEN) of the composition in
seconds, which the intro's pictures follow.
"""
import argparse
import os
import time

import derive
import mixer
import score as score_module

MUSIC_FOLDER = os.path.join(score_module.PROJECT, "assets", "audio", "muziek")
TIMING_FILE = os.path.join(score_module.PROJECT, "scripts", "ui", "intro_timing.gd")
## The constants of intro_timing.gd and the MOMENTEN they come from.
TIMING_NAMES = {"logo": "LOGO_AT", "verhaal": "CRAWL_AT", "hoogtepunt": "CLIMAX_AT", "duel": "DUEL_AT",
                "crash": "CRASH_AT", "rust": "REST_AT"}
## Seconds after the last bar the intro still lets the music ring out (then the menu).
RING_OUT = 1.0


def moment_seconds(moment, bar_seconds: float, beat_seconds: float) -> float:
    """A moment as a bar (its start) or (bar, beat), in seconds from the start."""
    bar, beat = moment if isinstance(moment, (tuple, list)) else (moment, 1.0)
    return (bar - 1) * bar_seconds + (beat - 1.0) * beat_seconds


def write_intro_timing(score: score_module.Score, composition_name: str, piece: mixer.Piece) -> None:
    moments = dict(score.moments)
    # without "rust" the story comes to rest at the start of the last bar
    moments.setdefault("rust", len(score.bars))
    missing = [moment for moment in TIMING_NAMES if moment not in moments]
    if missing:
        raise ValueError(f"{composition_name}: MOMENTEN misses {missing} (the intro needs them)")
    bar_seconds = score.bar_seconds
    lines = [
        "## The moments of the intro music (seconds into assets/audio/muziek/zwervr_intro.ogg).",
        f"## GENERATED by tools/muziek/build.py from the composition {composition_name}",
        f"## ({score.title}: {score.tempo:g} BPM, {len(score.bars)} bars of {bar_seconds:.5f} s); do not edit by hand.",
        "extends RefCounted",
        "",
    ]
    beat_seconds = 60.0 / score.tempo
    in_order = sorted(TIMING_NAMES, key=lambda moment: moment_seconds(moments[moment], bar_seconds, beat_seconds))
    for moment in in_order:
        lines.append(f"const {TIMING_NAMES[moment]} := {moment_seconds(moments[moment], bar_seconds, beat_seconds):.3f}")
    lines.append(f"const END_AT := {piece.bars_seconds + RING_OUT:.3f}")
    with open(TIMING_FILE, "w") as timing_file:
        timing_file.write("\n".join(lines) + "\n")
    print(f"geschreven: {TIMING_FILE}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("names", nargs="*", help="pieces to make (default: all)")
    parser.add_argument("--uit", default=MUSIC_FOLDER, help="the folder to write into")
    arguments = parser.parse_args()
    composition_name = score_module.active_name()
    score = score_module.load(composition_name)
    print(f"compositie: {composition_name} ({score.title}, {score.tempo:g} BPM, {len(score.bars)} maten)")
    menu_name = score_module.menu_name()
    menu_score = score_module.load(menu_name) if menu_name != composition_name else None
    if menu_score:
        print(f"menu: {menu_name} ({menu_score.title}, {menu_score.tempo:g} BPM, {len(menu_score.bars)} maten): "
              + ", ".join(make.__name__ for make in derive.SECONDARY_PIECES))
    fight_name = score_module.fight_name()
    fight_score = score_module.load(fight_name) if fight_name else None
    if fight_score:
        print(f"gevecht: {fight_name} ({fight_score.title}, {fight_score.tempo:g} BPM, {len(fight_score.bars)} maten)")
    pieces = derive.pieces(score, menu_score, fight_score)
    known = [piece.name for piece in pieces]
    unknown = [name for name in arguments.names if name not in known]
    if unknown:
        raise SystemExit(f"onbekend: {unknown}; kan maken: {known}")
    os.makedirs(arguments.uit, exist_ok=True)
    for index, piece in enumerate(pieces):
        if arguments.names and piece.name not in arguments.names:
            continue
        started = time.time()
        print(f"[ {index + 1}/{len(pieces)} ] {piece.name}", flush=True)
        mixer.write(piece, arguments.uit)
        if piece.name == "zwervr_intro" and os.path.abspath(arguments.uit) == os.path.abspath(MUSIC_FOLDER):
            write_intro_timing(score, composition_name, piece)
        print(f"        {time.time() - started:.1f} s", flush=True)


if __name__ == "__main__":
    main()
