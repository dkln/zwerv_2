def text_pixels(text, spacing=1):
    """Geeft lijst (col, row) pixels (row 0 = boven) en (breedte, hoogte)."""
    px = []
    cx = 0
    for ch in text:
        g = FONT.get(ch.upper(), FONT[" "])
        for r, line in enumerate(g):
            for c, v in enumerate(line):
                if v == "#":
                    px.append((cx + c, r))
        cx += 3 + spacing
    return px, (cx - spacing, 5)


