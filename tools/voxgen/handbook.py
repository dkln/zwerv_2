def _svg_tiles():
    """Top views of a ground tile and a building block, with the front side marked."""
    def tile(x0, label, size, inner, sub):
        s, y0 = 150, 50
        block = ""
        if inner:
            m = s * 8 / 48
            block = (f'<rect x="{x0 + m}" y="{y0 + m}" width="{s - 2 * m}" height="{s - 2 * m}" class="block"/>'
                     f'<text x="{x0 + s / 2}" y="{y0 + m + 16}" class="small" text-anchor="middle">blok 32 x 32</text>'
                     f'<text x="{x0 + s / 2}" y="{y0 + 17}" class="small muted" text-anchor="middle">rand 8</text>')
        return (f'<text x="{x0 + s / 2}" y="18" class="label" text-anchor="middle">{label}</text>'
                f'<text x="{x0 + s / 2}" y="38" class="small" text-anchor="middle">{size}</text>'
                f'<rect x="{x0}" y="{y0}" width="{s}" height="{s}" class="cell"/>{block}'
                f'<circle cx="{x0 + s / 2}" cy="{y0 + s / 2}" r="4" class="pivot"/>'
                f'<line x1="{x0}" y1="{y0 + s}" x2="{x0 + s}" y2="{y0 + s}" class="front"/>'
                f'<text x="{x0 + s / 2}" y="{y0 + s + 20}" class="small accent" text-anchor="middle">voorkant = +Z in Godot</text>'
                f'<text x="{x0 + s / 2}" y="{y0 + s + 38}" class="small muted" text-anchor="middle">{sub}</text>')
    return ('<svg class="narrow" viewBox="0 0 560 280" role="img" aria-label="Bovenaanzicht van een grond-tile en een gebouwblok">'
            + tile(40, "Grond-tile", "32 x 32 voxels = 4 x 4 m", False, "8 voxels hoog per meter")
            + tile(370, "Gebouwblok", "48 x 48 x 24 voxels", True, "24 voxels = 1 verdieping (3 m)")
            + '<text x="280" y="272" class="small muted" text-anchor="middle">● = draaipunt (midden, onderkant) · voorkant = laagste Y in MagicaVoxel</text></svg>')


def _svg_slots():
    """The 255 palette slots as a bar with the reserved water and flag ranges."""
    w = 760 / 255
    parts = []
    for lo, hi, cls, label in [(1, 224, "slot-normal", "1 – 224: gewone kleuren"),
                               (225, 232, "slot-water", "225 – 232: water"),
                               (233, 248, "slot-flag", "233 – 248: vlag"),
                               (249, 255, "slot-free", "")]:
        x = 20 + (lo - 1) * w
        parts.append(f'<rect x="{x:.1f}" y="20" width="{(hi - lo + 1) * w:.1f}" height="34" class="{cls}"/>')
        if label:
            tx = x + (hi - lo + 1) * w / 2
            anchor = "middle"
            y = 76 if lo < 225 else (92 if lo == 225 else 76)
            parts.append(f'<text x="{tx:.1f}" y="{y}" class="small" text-anchor="{anchor}">{label}</text>')
    return ('<svg viewBox="0 0 800 100" role="img" aria-label="Paletplekken 1 tot 255">' + "".join(parts) + '</svg>')


def _swatches(theme):
    rows = legend(os.path.join(PALETTE_DIR, f"palet_{theme}.vox"))
    cells = []
    for slot, rgb, names, mat in rows:
        hexc = "#%02x%02x%02x" % rgb
        light = (0.299 * rgb[0] + 0.587 * rgb[1] + 0.114 * rgb[2]) > 150
        label = MATERIALS.get(mat, (mat, ""))[0]
        name = ", ".join(names)
        cells.append(
            f'<div class="sw" data-search="{html.escape(name + " " + label + " " + str(slot) + " " + hexc)}">'
            f'<div class="chip{" light" if light else ""}" style="background:{hexc}"><span class="nr">{slot}</span></div>'
            f'<div class="meta"><div class="name">{html.escape(name)}</div>'
            f'<div class="sub"><code>{hexc}</code><span class="badge m-{mat}">{label}</span></div></div></div>')
    return f'<div class="swatches">{"".join(cells)}</div>'


def _material_key():
    items = "".join(f'<li><span class="badge m-{k}">{v[0]}</span> {html.escape(v[1])}</li>' for k, v in MATERIALS.items())
    return f'<ul class="key">{items}</ul>'


