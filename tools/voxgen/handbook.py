# ------------------------------------------------------------------ markdown subset

def _inline(text):
    text = html.escape(text, quote=False)
    text = re.sub(r"`([^`]+)`", r"<code>\1</code>", text)
    text = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", text)
    return text


def _slug(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def markdown(md):
    """HTML for the Markdown subset used in docs/MAGICAVOXEL.md, plus the h2 list
    [(id, title)] for the table of contents."""
    out, toc = [], []
    lines = md.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith("```"):
            j = i + 1
            while j < len(lines) and not lines[j].startswith("```"):
                j += 1
            out.append("<pre><code>" + html.escape("\n".join(lines[i + 1:j])) + "</code></pre>")
            i = j + 1
        elif m := re.match(r"(#{1,3}) (.*)", line):
            level, title = len(m.group(1)), m.group(2)
            if level == 1:
                i += 1
                continue   # the page has its own title
            ident = _slug(title)
            if level == 2:
                toc.append((ident, title))
            out.append(f'<h{level} id="{ident}">{_inline(title)}</h{level}>')
            i += 1
        elif line.startswith("|"):
            rows = []
            while i < len(lines) and lines[i].startswith("|"):
                cells = [c.strip() for c in lines[i].strip().strip("|").split("|")]
                if not all(re.fullmatch(r":?-+:?", c) for c in cells):
                    rows.append(cells)
                i += 1
            head = "".join(f"<th>{_inline(c)}</th>" for c in rows[0])
            body = "".join("<tr>" + "".join(f"<td>{_inline(c)}</td>" for c in r) + "</tr>" for r in rows[1:])
            out.append(f'<div class="table"><table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table></div>')
        elif re.match(r"(\s*)(- |\d+\. )", line):
            out.append(_list(lines, i))
            while i < len(lines) and (re.match(r"\s*(- |\d+\. )", lines[i]) or (lines[i].startswith("  ") and lines[i].strip())):
                i += 1
        elif line.strip():
            para = [line]
            i += 1
            while i < len(lines) and lines[i].strip() and not re.match(r"(#|\||```|\s*- |\d+\. )", lines[i]):
                para.append(lines[i])
                i += 1
            out.append("<p>" + _inline(" ".join(p.strip() for p in para)) + "</p>")
        else:
            i += 1
    return "\n".join(out), toc


def _list(lines, i):
    """Nested <ul>/<ol> starting at line i (items may continue on indented lines)."""
    items = []   # (indent, ordered, text)
    while i < len(lines):
        m = re.match(r"(\s*)(- |\d+\. )(.*)", lines[i])
        if m:
            items.append([len(m.group(1)), m.group(2) != "- ", m.group(3)])
        elif lines[i].startswith("  ") and lines[i].strip() and items:
            items[-1][2] += " " + lines[i].strip()
        else:
            break
        i += 1

    def build(k, indent):
        tag = "ol" if items[k][1] else "ul"
        parts = [f"<{tag}>"]
        while k < len(items) and items[k][0] >= indent:
            if items[k][0] > indent:
                sub, k = build(k, items[k][0])
                parts[-1] = parts[-1][:-5] + sub + "</li>"
                continue
            parts.append(f"<li>{_inline(items[k][2])}</li>")
            k += 1
        parts.append(f"</{tag}>")
        return "".join(parts), k

    return build(0, items[0][0])[0]


