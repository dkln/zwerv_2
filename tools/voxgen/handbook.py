def write_handbook(path=TARGET):
    """Write the HTML handbook; returns its path."""
    body, toc = markdown(open(SOURCE).read())
    # figures right after the headings they illustrate
    body = body.replace('<h2 id="2-een-nieuwe-tile-maken">',
                        '<div class="figure">' + _svg_tiles() + '</div>\n<h2 id="2-een-nieuwe-tile-maken">', 1)
    body = body.replace('<h2 id="4-materialen">',
                        '<div class="figure">' + _svg_slots() + '</div>\n<h2 id="4-materialen">', 1)
    tabs = "".join(f'<button data-theme="{t}" aria-selected="false">{t.capitalize()}</button>' for t in THEMES)
    palettes = "".join(f'<section class="palette" id="pal-{t}" hidden>{_swatches(t)}</section>' for t in THEMES)
    toc.append(("paletten", "Paletten"))
